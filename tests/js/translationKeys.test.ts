/// <reference types="node" />
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vite-plus/test';
import messages from '../../lang/es.json';
import { findTranslationCalls } from './support/translationCalls';

// Spec 001, R2 (D-091): t() falls back to the English key at runtime, so this guard is
// what breaks CI when a key is missing from lang/es.json, is not a string literal, or
// t escapes the scan: a renamed import, or the identifier t used for anything else.
const root = fileURLToPath(new URL('../../resources/js', import.meta.url));

// Vendor code (shadcn-vue), files generated by Wayfinder, and the helper itself,
// which is where t is declared.
const excludedFolders = ['components/ui/', 'actions/', 'routes/', 'wayfinder/'];
const excludedFiles = ['lib/i18n.ts'];

const scannedFiles = (
    readdirSync(root, { recursive: true, encoding: 'utf8' }) as string[]
)
    .map((path) => path.replaceAll('\\', '/'))
    .filter((path) => /\.(ts|vue)$/.test(path))
    .filter((path) => !excludedFolders.some((dir) => path.startsWith(dir)))
    .filter((path) => !excludedFiles.includes(path))
    .sort();

const translations: Record<string, string> = messages;

describe('t() keys in resources/js', () => {
    it('scans the app files and skips the excluded ones', () => {
        expect(scannedFiles).toContain('pages/Dashboard.vue');
        expect(scannedFiles).not.toContain('lib/i18n.ts');
        expect(
            scannedFiles.filter((path) => path.startsWith('components/ui/')),
        ).toEqual([]);
    });

    it('uses only literal keys that exist in lang/es.json', () => {
        const problems = scannedFiles.flatMap((path) => {
            const source = readFileSync(`${root}/${path}`, 'utf8');
            const { calls, evasions } = findTranslationCalls(source, path);

            return [
                ...evasions.map(({ line, code, reason }) =>
                    reason === 'import'
                        ? `${path}:${line} hides t from this scan: ${code}`
                        : `${path}:${line} t is reserved for the translation helper; rename it: ${code}`,
                ),
                ...calls.flatMap(({ line, key, code }) => {
                    if (key === null) {
                        return [
                            `${path}:${line} key is not a string literal: ${code}`,
                        ];
                    }

                    return Object.hasOwn(translations, key)
                        ? []
                        : [`${path}:${line} missing in lang/es.json: "${key}"`];
                }),
            ];
        });

        expect(problems).toEqual([]);
    });
});
